const STORAGE_KEY = "mq_lang";

function detectInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "zh-CN" || saved === "en-US") return saved;
  } catch {
    // ignore storage errors
  }
  return "zh-CN";
}

